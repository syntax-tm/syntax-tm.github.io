const numberDots = 100;
const letterDelays = [25, 41, 54, 65, 76, 84, 92, 99, 106];
const letters = "Dreamcast".split('');

function SpiralMask({index}: {index: number}) {

  const duration = index * (0.026 * 0.4);
  const distance = (100 / numberDots) * (index + 1);

  // animation-duration: ${index * (0.026 * 0.4)}s;
  // offset-distance: ${(100 / numberDots) * (index + 1)}%`;
  const spiralStyle: React.CSSProperties = {
    animationDuration: `${duration}s`,
    offsetDistance: `${distance}%`,
  };

  return <div className="spiral-mask" style={spiralStyle} />;
}

function BootLetter({index, letter}: {index: number, letter: string}) {

  // animation-delay: ${letterDelays[index] / 31 + 0.9}s;
  // animation-duration: ${0.07 * (letters.length - index) + 0.1}s;

  const delay = letterDelays[index] / 31 + 0.9;
  const duration = 0.07 * (letters.length - index) + 0.1;

  const letterStyle: React.CSSProperties = {
    animationDelay: `${delay}s`,
    animationDuration: `${duration}s`,
  };

  return <span className="letter" style={letterStyle}>{letter}</span>;
}

